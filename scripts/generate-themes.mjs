#!/usr/bin/env node
// Generates lib/themes.generated.ts from Omarchy's theme palettes.
//
//   node scripts/generate-themes.mjs [/path/to/omarchy/themes]
//
// Default source: /usr/share/omarchy/themes (Omarchy, Arch Linux). The output is committed, so
// CI and other machines never need Omarchy installed; re-run only to pick up palette changes.
//
// Each theme's colors.toml is mapped onto the site's 14 colour tokens (see app/globals.css). Any
// mapped colour that fails its contrast requirement is nudged toward the ink/bg until it passes,
// so every theme keeps WCAG AA for text (4.5:1) and 3:1 for decorative accents.
// tests/themes.test.ts re-checks the committed output independently.

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const SRC = process.argv[2] ?? "/usr/share/omarchy/themes";
const ROOT = new URL("..", import.meta.url).pathname;
const OUT = join(ROOT, "lib/themes.generated.ts");

// ---------- colour maths (sRGB, WCAG 2.x) ----------
const hex = (s) => {
  const m = /^#?([0-9a-f]{6})$/i.exec(s.trim());
  if (!m) throw new Error(`bad colour ${s}`);
  const n = parseInt(m[1], 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
};
const toHex = (c) => "#" + c.map((v) => Math.round(v).toString(16).padStart(2, "0")).join("");
const lin = (v) => {
  v /= 255;
  return v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4;
};
const lum = (c) => 0.2126 * lin(c[0]) + 0.7152 * lin(c[1]) + 0.0722 * lin(c[2]);
export const contrast = (a, b) => {
  const [x, y] = [lum(hex(a)), lum(hex(b))].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
};
const mix = (a, b, t) => toHex(hex(a).map((v, i) => v + (hex(b)[i] - v) * t));

/** Move `c` toward `target` in 2% steps until it reaches `min` contrast against `against`. */
function ensure(c, against, min, target) {
  for (let t = 0; t <= 1.0001; t += 0.02) {
    const m = mix(c, target, t);
    if (contrast(m, against) >= min) return m;
  }
  return target;
}
/** Whichever of the candidates contrasts best with `bg`. */
const best = (bg, ...cands) => cands.reduce((a, b) => (contrast(b, bg) > contrast(a, bg) ? b : a));

// ---------- parse colors.toml (flat `key = "value"` lines) ----------
function parse(file) {
  const out = {};
  for (const line of readFileSync(file, "utf8").split("\n")) {
    const m = /^\s*([a-z_]+)\s*=\s*"([^"]*)"/.exec(line);
    if (m) out[m[1]] = m[2];
  }
  return out;
}

const LABELS = { "flexoki-light": "Flexoki Light", "catppuccin-latte": "Catppuccin Latte" };
const label = (id) =>
  LABELS[id] ?? id.split("-").map((w) => w[0].toUpperCase() + w.slice(1)).join(" ");

function mapTheme(id, p) {
  const dark = p.mode !== "light";
  const bg = p.background;
  const black = "#000000";
  const white = "#ffffff";
  const far = dark ? white : black; // the direction "more contrast" lies in

  const ink = ensure(dark ? p.bright_foreground : p.foreground, bg, 7, far);
  const inkMuted = ensure(p.foreground, bg, 4.5, ink);
  const surface = dark ? p.lighter_background : p.dark_background;
  const brand = ensure(p.accent, bg, 4.5, far);
  const brandSoft = ensure(mix(brand, ink, 0.25), bg, 4.5, far);
  // the site's "gold": prefer the theme's yellow, then orange, whichever reads better
  const accent = ensure(best(bg, p.yellow, p.orange ?? p.bright_yellow, p.bright_yellow), bg, 3, far);
  const accentInk = best(accent, bg, ink, black, white);
  const footerBg = dark ? p.darker_background : p.dark_background;
  const footerFg = ensure(ink, footerBg, 7, far);

  return {
    id,
    label: label(id),
    mode: dark ? "dark" : "light",
    swatch: [bg, brand, accent],
    vars: {
      "--color-bg": bg,
      "--color-surface": surface,
      "--color-ink": ink,
      "--color-ink-muted": inkMuted,
      "--color-rule": ensure(p.selection, bg, 1.4, far),
      "--color-brand": brand,
      "--color-brand-soft": brandSoft,
      "--color-brand-warm": dark ? p.dark_background : p.lighter_background,
      "--color-accent": accent,
      "--color-accent-ink": accentInk,
      "--color-footer-bg": footerBg,
      "--color-footer-fg": footerFg,
      "--color-footer-fg-muted": ensure(mix(footerFg, footerBg, 0.3), footerBg, 4.5, footerFg),
      "--color-footer-rule": brand,
    },
    hero: existsSync(join(ROOT, "public/themes", `${id}.webp`)) ? `/themes/${id}.webp` : null,
    heroPhone: existsSync(join(ROOT, "public/themes", `${id}-phone.webp`)) ? `/themes/${id}-phone.webp` : null,
  };
}

const themes = readdirSync(SRC)
  .filter((d) => existsSync(join(SRC, d, "colors.toml")))
  .sort()
  .map((d) => mapTheme(d, parse(join(SRC, d, "colors.toml"))));

const body = `// GENERATED by scripts/generate-themes.mjs from Omarchy's theme palettes. Do not edit by hand.
// Re-run: node scripts/generate-themes.mjs

import type { SiteTheme } from "./themes";

export const OMARCHY_THEMES: readonly SiteTheme[] = ${JSON.stringify(themes, null, 2)};
`;
writeFileSync(OUT, body);
console.log(`wrote ${themes.length} themes to ${OUT}`);
for (const t of themes) {
  console.log(
    `${t.id.padEnd(18)} ${t.mode.padEnd(5)} ink ${contrast(t.vars["--color-ink"], t.vars["--color-bg"]).toFixed(1)}`.padEnd(40),
    `brand ${contrast(t.vars["--color-brand"], t.vars["--color-bg"]).toFixed(1)}  hero ${t.hero ? "yes" : "no"}  phone ${t.heroPhone ? "yes" : "no"}`,
  );
}
